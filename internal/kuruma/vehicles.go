// Lookup returns the vehicle with the given Name.
func Lookup(name string) (Vehicle, bool) {
	for _, v := range All {
		if v.Name == name {
			return v, true
		}
	}
	return Vehicle{}, false
}

// Random returns a generator of random vehicles that never repeats the
// previous one.
func Random() func() Vehicle {
	prev := -1
	return func() Vehicle {
		i := rand.N(len(All))
		if prev >= 0 && len(All) > 1 {
			i = (prev + 1 + rand.N(len(All)-1)) % len(All)
		}
		prev = i
		return All[i]
	}
}
